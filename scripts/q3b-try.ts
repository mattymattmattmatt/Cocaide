import { LocalKernel } from "../src/ask/kernel";
import { getOC, loadOC } from "../src/kernel";
import { autoDetail } from "../src/ask/detail/auto";
import { composeDrawing } from "../src/drafting/compose";
import { bearingPlate } from "../tests/detail-fixtures";
import { findingsOf } from "../src/ask/detail/auto";
await loadOC();
const kernel = new LocalKernel(getOC);
import { makePlan } from "../src/ask/detail/auto";
let t = Date.now();
await makePlan(bearingPlate(), kernel, {});
console.log("plan", Date.now() - t);
t = Date.now();
const r = await autoDetail(bearingPlate(), kernel, { date: "2026-11-05" });
console.log("auto", Date.now() - t);
const st = r.execution.state;
t = Date.now();
for (let i = 0; i < 5; i++) composeDrawing(r.doc, { measurements: st.check.measurements, geometry: st.geometry });
console.log("compose x5", Date.now() - t);
t = Date.now();
findingsOf(st, r.plan);
console.log("findings", Date.now() - t);
t = Date.now();
await kernel.check(r.doc);
console.log("check", Date.now() - t);
