// Writes src/geom/text/fontData.ts: the glyph outlines sketch text uses, read
// from the bundled fonts (assets/fonts, SIL Open Font Licence) with the
// TrueType reader in src/geom/text/ttf.ts. Run it again after changing the
// fonts or the characters below:
//
//   npx tsx scripts/build-font.ts
//
// Each glyph is its advance and its contours; a contour is its points in font
// units, "x,y" on the curve and "~x,y" a quadratic control point.

import { readFileSync, writeFileSync } from "node:fs";
import { readTtf } from "../src/geom/text/ttf";

const FONTS = [
  { key: "sans", file: "assets/fonts/LiberationSans-Regular.ttf", label: "Sans" },
  { key: "sans-bold", file: "assets/fonts/LiberationSans-Bold.ttf", label: "Sans Bold" },
];

/** Printable ASCII, Latin-1 and the signs drawings use. */
const CODES = [
  ...Array.from({ length: 95 }, (_, i) => 32 + i),
  ...Array.from({ length: 96 }, (_, i) => 160 + i),
  0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x20ac, 0x2122, 0x2126, 0x2190, 0x2191, 0x2192, 0x2193, 0x2206, 0x2212, 0x221e, 0x2248, 0x2260, 0x2264, 0x2265, 0x2300, 0x2032, 0x2033, 0x03a9, 0x03bc, 0x03c0,
];

const out: string[] = [];
out.push("// Generated by scripts/build-font.ts from the fonts in assets/fonts (SIL Open Font Licence 1.1, see");
out.push("// assets/fonts/LICENSE-OFL.txt): do not edit by hand. Glyph outlines in font units; a contour's points");
out.push('// are "x,y" on the curve, "~x,y" a quadratic control point.');
out.push("");
out.push("export interface FontData {");
out.push("  label: string;");
out.push("  unitsPerEm: number;");
out.push("  ascender: number;");
out.push("  descender: number;");
out.push("  /** Character -> [advance, contours]. */");
out.push("  glyphs: Record<string, [number, string[]]>;");
out.push("}");
out.push("");
out.push("export const FONT_DATA: Record<string, FontData> = {");
for (const f of FONTS) {
  const font = readTtf(new Uint8Array(readFileSync(f.file)));
  const glyphs: string[] = [];
  for (const code of CODES) {
    const g = font.glyphIndex(code);
    if (g === 0 && code !== 32) continue;
    const glyph = font.glyph(g);
    const contours = glyph.contours.map((c) => c.map((p) => `${p.on ? "" : "~"}${p.x},${p.y}`).join(" "));
    glyphs.push(`    ${JSON.stringify(String.fromCodePoint(code))}: [${glyph.advance}, ${JSON.stringify(contours)}],`);
  }
  out.push(`  ${JSON.stringify(f.key)}: {`);
  out.push(`    label: ${JSON.stringify(f.label)},`);
  out.push(`    unitsPerEm: ${font.unitsPerEm},`);
  out.push(`    ascender: ${font.ascender},`);
  out.push(`    descender: ${font.descender},`);
  out.push("    glyphs: {");
  out.push(...glyphs.map((g) => `  ${g}`));
  out.push("    },");
  out.push("  },");
}
out.push("};");
writeFileSync("src/geom/text/fontData.ts", out.join("\n") + "\n");
console.log("wrote src/geom/text/fontData.ts");
